/**
 * IndexedDB-backed media store for journal photos and short videos.
 *
 * Journal entries are persisted to `localStorage`, which cannot hold binary
 * blobs. Photos and videos therefore live here, keyed by a generated
 * `mediaId`; the serializable store keeps only a light reference.
 *
 * Everything is local-first: no uploads, no network. Object URLs are minted on
 * demand and must be revoked by the caller (see `useMediaUrl`).
 */

import type { MediaKind } from '../types/domain'

/** Name of the IndexedDB database holding media blobs. */
const DB_NAME = 'urbanhound.media'

/** Schema version of the media database. */
const DB_VERSION = 1

/** Object store that maps `mediaId` to a `Blob`. */
const STORE_NAME = 'blobs'

/** Longest edge, in pixels, that a stored photo is downscaled to. */
const PHOTO_MAX_EDGE = 1400

/** JPEG quality applied when compressing photos. */
const PHOTO_QUALITY = 0.82

/** Videos larger than this are rejected to protect device storage. */
export const MAX_VIDEO_BYTES = 40 * 1024 * 1024

/** A stored blob together with its bookkeeping metadata. */
interface StoredMedia {
  mediaId: string
  kind: MediaKind
  mimeType: string
  blob: Blob
  createdAt: string
}

/**
 * Open (or create) the media database.
 *
 * @returns A promise resolving to the open database.
 */
function openDatabase(): Promise<IDBDatabase> {
  return new Promise((resolve, reject) => {
    if (typeof indexedDB === 'undefined') {
      reject(new Error('IndexedDB is unavailable in this environment.'))
      return
    }
    const request = indexedDB.open(DB_NAME, DB_VERSION)
    request.onupgradeneeded = () => {
      const database = request.result
      if (!database.objectStoreNames.contains(STORE_NAME)) {
        database.createObjectStore(STORE_NAME, { keyPath: 'mediaId' })
      }
    }
    request.onsuccess = () => resolve(request.result)
    request.onerror = () => reject(request.error ?? new Error('Failed to open media store.'))
  })
}

/**
 * Run a transaction against the media store.
 *
 * @param mode - Transaction mode.
 * @param run - Callback receiving the object store.
 * @returns A promise resolving with the callback's result.
 */
async function withStore<T>(
  mode: IDBTransactionMode,
  run: (store: IDBObjectStore) => IDBRequest<T>,
): Promise<T> {
  const database = await openDatabase()
  return new Promise<T>((resolve, reject) => {
    const transaction = database.transaction(STORE_NAME, mode)
    const store = transaction.objectStore(STORE_NAME)
    const request = run(store)
    request.onsuccess = () => resolve(request.result)
    request.onerror = () => reject(request.error ?? new Error('Media transaction failed.'))
    transaction.oncomplete = () => database.close()
  })
}

/**
 * Downscale and re-encode an image file into a compact JPEG blob.
 *
 * @param file - The original image file.
 * @returns A promise resolving to the compressed JPEG blob.
 */
async function compressPhoto(file: File): Promise<Blob> {
  if (typeof createImageBitmap === 'undefined') {
    return file
  }
  const bitmap = await createImageBitmap(file)
  const scale = Math.min(1, PHOTO_MAX_EDGE / Math.max(bitmap.width, bitmap.height))
  const width = Math.max(1, Math.round(bitmap.width * scale))
  const height = Math.max(1, Math.round(bitmap.height * scale))
  const canvas = document.createElement('canvas')
  canvas.width = width
  canvas.height = height
  const context = canvas.getContext('2d')
  if (!context) {
    bitmap.close()
    return file
  }
  context.drawImage(bitmap, 0, 0, width, height)
  bitmap.close()
  const blob = await new Promise<Blob | null>((resolve) =>
    canvas.toBlob((result) => resolve(result), 'image/jpeg', PHOTO_QUALITY),
  )
  return blob ?? file
}

/**
 * Persist a user-selected file as journal media.
 *
 * Photos are compressed; videos are stored as-is but size-limited. The caller
 * supplies a fresh `mediaId` so the store can reference the blob immediately.
 *
 * @param mediaId - Identifier generated by the caller.
 * @param file - The selected photo or video file.
 * @returns A promise resolving to the stored media's kind and mime type.
 * @throws When the file is a video larger than {@link MAX_VIDEO_BYTES}.
 */
export async function saveMedia(
  mediaId: string,
  file: File,
): Promise<{ kind: MediaKind; mimeType: string }> {
  const isVideo = file.type.startsWith('video/')
  if (isVideo && file.size > MAX_VIDEO_BYTES) {
    throw new Error('That video is too large to keep on-device. Try a shorter clip.')
  }
  const blob = isVideo ? file : await compressPhoto(file)
  const record: StoredMedia = {
    mediaId,
    kind: isVideo ? 'VIDEO' : 'PHOTO',
    mimeType: blob.type || file.type || 'application/octet-stream',
    blob,
    createdAt: new Date().toISOString(),
  }
  await withStore('readwrite', (store) => store.put(record))
  return { kind: record.kind, mimeType: record.mimeType }
}

/**
 * Load a stored blob by identifier.
 *
 * @param mediaId - Identifier of the media to load.
 * @returns A promise resolving to the blob, or `null` when absent.
 */
export async function loadMedia(mediaId: string): Promise<Blob | null> {
  const record = await withStore<StoredMedia | undefined>('readonly', (store) =>
    store.get(mediaId),
  )
  return record?.blob ?? null
}

/**
 * Delete a stored blob.
 *
 * @param mediaId - Identifier of the media to remove.
 * @returns A promise that resolves when the deletion completes.
 */
export async function deleteMedia(mediaId: string): Promise<void> {
  await withStore('readwrite', (store) => store.delete(mediaId))
}

/**
 * Delete several stored blobs, ignoring individual failures.
 *
 * @param mediaIds - Identifiers to remove.
 * @returns A promise that resolves once every deletion has been attempted.
 */
export async function deleteManyMedia(mediaIds: string[]): Promise<void> {
  await Promise.all(mediaIds.map((mediaId) => deleteMedia(mediaId).catch(() => undefined)))
}
